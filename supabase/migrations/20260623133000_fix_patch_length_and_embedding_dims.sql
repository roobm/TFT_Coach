-- Fix two issues found at runtime against the local stack:
--  1. Riot's game_version (stored in match_history.patch) is far longer than the
--     original varchar(10), so every insert failed with "value too long".
--  2. The local LM Studio embedding model returns 768-dim vectors, but the
--     embedding columns were vector(1536) (OpenAI's size), so similarity search
--     failed with "different vector dimensions 1536 and 768".

-- 1. Widen the patch/version column.
alter table match_history alter column patch type varchar(50);

-- 2. Re-dimension the embedding columns to match the local model (768).
--    Existing rows hold 1536-dim vectors generated by a different model; they are
--    incompatible with the local model and must be re-seeded, so clear them first.
--    ivfflat indexes are tied to the column type, so drop and recreate them.
truncate table round_logs;
truncate table tft_patch_data;

drop index if exists tft_patch_data_embedding_idx;
alter table tft_patch_data alter column embedding type vector(768);
create index tft_patch_data_embedding_idx
    on tft_patch_data using ivfflat (embedding vector_cosine_ops) with (lists = 100);

drop index if exists round_logs_embedding_idx;
alter table round_logs alter column embedding type vector(768);
create index round_logs_embedding_idx
    on round_logs using ivfflat (embedding vector_cosine_ops) with (lists = 100);
